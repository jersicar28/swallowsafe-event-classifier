def bandpass_filter(data, lowcut=0.5, highcut=20.0, fs=50, order=2):
    """Applies a Butterworth bandpass filter to remove DC offset & high-frequency noise."""
    nyquist = 0.5 * fs
    low = lowcut / nyquist
    high = highcut / nyquist
    b, a = butter(order, [low, high], btype='band')
    return filtfilt(b, a, data)

def preprocess_block(df):
    """Cleans time series and applies filtering to piezo channels."""
    # Convert Time_ms relative to start of recording
    df['Time_sec'] = (df['Time_ms'] - df['Time_ms'].iloc[0]) / 1000.0

    # Filter sensor channels
    for col in ['Piezo1_V', 'Piezo2_V', 'Piezo3_V']:
        if col in df.columns:
            # Demean to center signal around zero
            demeaned = df[col] - df[col].mean()
            df[f'{col}_clean'] = bandpass_filter(demeaned, fs=SAMPLING_RATE_HZ)

    return df

