def extract_features(window_df):
    """Extracts time and frequency domain features from a 5-second window."""
    features = {}
    signal_cols = ['Piezo1_V_clean', 'Piezo2_V_clean', 'Piezo3_V_clean', 'Mic_Level']

    for col in signal_cols:
        if col not in window_df.columns:
            continue
        sig = window_df[col].values

        # Time-domain features
        features[f'{col}_mean'] = np.mean(sig)
        features[f'{col}_std'] = np.std(sig)
        features[f'{col}_max'] = np.max(sig)
        features[f'{col}_min'] = np.min(sig)
        features[f'{col}_rms'] = np.sqrt(np.mean(sig**2))
        features[f'{col}_p2p'] = np.ptp(sig)  # Peak-to-peak amplitude

        # Frequency-domain feature (FFT Energy)
        fft_vals = np.abs(np.fft.rfft(sig))
        features[f'{col}_energy'] = np.sum(fft_vals**2) / len(fft_vals)

    return features

