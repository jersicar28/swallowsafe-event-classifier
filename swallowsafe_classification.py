# 5. EVENT ALIGNMENT + DATASET ASSEMBLY
# ==========================================
EVENT_WIN_SEC = 3.0   # length of each extracted window (centered on the event)
SEARCH_SEC = 3.0      # how far (±) an event may drift from its scheduled time
SMOOTH_SEC = 0.5      # smoothing for the activity envelope

# Optional manual fixes: {block_file_name: {protocol_slot_index: event_center_in_seconds}}
# Slot indexes: 0=talk, 2=talk, 4=water, 6=water, 8=cough, 10=cough
MANUAL_OVERRIDES = {
    # 'block3_t6.csv': {8: 44.2},   # example: first cough actually centered at 44.2 s
}

ACTIVE_SLOTS = [(i, lbl) for i, lbl in enumerate(PROTOCOL_LABELS) if lbl != 'break']

def activity_envelope(df):
    """Combined, smoothed energy across all cleaned channels."""
    energy = np.sum([df[c].values**2 for c in CLEAN_COLS if c in df.columns], axis=0)
    k = int(SMOOTH_SEC * SAMPLING_RATE_HZ)
    return np.convolve(energy, np.ones(k) / k, mode='same')

def align_events(df, block_name):
    """Find each scheduled event near its expected time, keeping protocol order."""
    fs = SAMPLING_RATE_HZ
    env = activity_envelope(df)
    cum = np.concatenate([[0], np.cumsum(env)])
    half = int(EVENT_WIN_SEC * fs / 2)
    search = int(SEARCH_SEC * fs)
    n = len(env)
    overrides = MANUAL_OVERRIDES.get(block_name, {})

    events, prev_end = [], 0
    for slot, label in ACTIVE_SLOTS:
        if slot in overrides:
            c = int(overrides[slot] * fs)
        else:
            nominal = int((slot * WINDOW_SIZE_SEC + WINDOW_SIZE_SEC / 2) * fs)
            lo = max(nominal - search, prev_end + half, half)
            hi = min(nominal + search, n - half)
            if lo >= hi:
                print(f"  ⚠ {block_name}: no room for '{label}' (slot {slot}) — block too short, skipped")
                continue
            centers = np.arange(lo, hi)
            window_energy = cum[centers + half] - cum[centers - half]
            c = centers[np.argmax(window_energy)]
        events.append({'start': c - half, 'end': c + half, 'label': label, 'slot': slot})
        prev_end = c + half

    # Break windows: centered in the quiet gap after each event
    breaks = []
    for i, ev in enumerate(events):
        gap_start = ev['end']
        gap_end = events[i + 1]['start'] if i + 1 < len(events) else n
        if gap_end - gap_start >= 2 * half:
            mid = (gap_start + gap_end) // 2
            breaks.append({'start': mid - half, 'end': mid + half, 'label': 'break', 'slot': ev['slot'] + 1})

    return sorted(events + breaks, key=lambda e: e['start']), env

def plot_alignment(df, segments, env, block_name):
    """Shaded detected windows over the activity envelope — use this to sanity-check."""
    colors = {'talk': 'tab:blue', 'water': 'tab:green', 'cough': 'tab:red', 'break': 'lightgray'}
    t = df['Time_sec'].values
    fig, ax = plt.subplots(figsize=(14, 3))
    ax.plot(t, env, color='black', linewidth=0.8)
    for seg in segments:
        ax.axvspan(t[seg['start']], t[min(seg['end'], len(t) - 1)],
                   color=colors[seg['label']], alpha=0.35)
        ax.text((t[seg['start']] + t[min(seg['end'], len(t) - 1)]) / 2, ax.get_ylim()[1] * 0.9,
                f"{seg['label']}\n(slot {seg['slot']})", ha='center', va='top', fontsize=7)
    for t_mark in range(0, int(t[-1]) + 1, 5):   # original fixed schedule for comparison
        ax.axvline(t_mark, color='black', linestyle='--', alpha=0.15)
    ax.set_title(f'Event alignment — {block_name}')
    ax.set_xlabel('Time (s)')
    ax.set_ylabel('Activity')
    plt.tight_layout()
    plt.show()

def build_dataset_from_blocks(file_paths, show_plots=True):
    all_features, all_labels, all_groups = [], [], []
    for file_path in file_paths:
        block_name = os.path.basename(file_path)
        df = preprocess_block(pd.read_csv(file_path))
        segments, env = align_events(df, block_name)

        if show_plots:
            plot_alignment(df, segments, env, block_name)

        for seg in segments:
            all_features.append(extract_features(df.iloc[seg['start']:seg['end']]))
            all_labels.append(seg['label'])
            all_groups.append(block_name)

        counts = pd.Series([s['label'] for s in segments]).value_counts().to_dict()
        print(f"  {block_name}: {counts}")

    return pd.DataFrame(all_features), np.array(all_labels), np.array(all_groups)

