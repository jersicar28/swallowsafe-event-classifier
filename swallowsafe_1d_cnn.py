"""## 3. Causal preprocessing
Everything in this section can be computed one sample at a time, which is what the real-time classifier in section 8 does.
"""

def causal_bandpass(x, sos=SOS):
    """Causal IIR bandpass. Initial state = steady state for the first value (avoids a start-up spike)."""
    zi = sosfilt_zi(sos) * x[0]
    y, _ = sosfilt(sos, x, zi=zi)
    return y

def mic_valid_causal(mic, low=MIC_BAD_LOW, high=MIC_BAD_HIGH, hold=MIC_HOLD):
    """1 if no glitch in the current or previous hold-1 samples, else 0."""
    bad = ~np.isfinite(mic) | (mic < low) | (mic > high)
    recent_bad = np.convolve(bad.astype(float), np.ones(hold))[: len(mic)]
    return (recent_bad == 0).astype(np.float32)

def preprocess_block(raw):
    """raw (T,4) -> features (T,5) BEFORE normalization: p1..p3 filtered, mic (nan where invalid), mic_valid."""
    T = len(raw)
    x = np.empty((T, N_CH), np.float64)
    for c in range(3):
        x[:, c] = causal_bandpass(raw[:, c])
    valid = mic_valid_causal(raw[:, 3])
    x[:, 3] = np.where(valid > 0, raw[:, 3], np.nan)
    x[:, 4] = valid
    return x

def fit_norm(feat_list):
    allx = np.concatenate(feat_list)
    mean = np.nanmean(allx[:, :4], axis=0)
    std = np.nanstd(allx[:, :4], axis=0) + 1e-6
    return {"mean": mean.astype(np.float32), "std": std.astype(np.float32)}

def normalize(feat, norm):
    y = feat.astype(np.float32).copy()
    y[:, :4] = (y[:, :4] - norm["mean"]) / norm["std"]
    y[:, 3] = np.nan_to_num(y[:, 3]) * y[:, 4]      # invalid mic -> 0
    return y

