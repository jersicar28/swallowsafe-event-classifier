"""## 9. Real-time classifier
The classifier takes one sample at a time: `update(p1, p2, p3, mic)` returns `(label, probabilities)`. It keeps the filter state, a 2 s ring buffer and the probability-smoothing history. On a laptop CPU each call takes about a millisecond. On weaker hardware, call `update(..., run_model=False)` for most samples and run the network every few samples, e.g. every 5 (10 Hz).
"""

class RealTimeSwallowClassifier:
    def __init__(self, path=MODEL_PATH, device="cpu"):
        ck = torch.load(path, map_location=device, weights_only=True)
        cfg = ck["config"]
        self.cfg, self.classes, self.device = cfg, cfg["classes"], torch.device(device)
        self.model = SwallowCNN(**cfg["model_kwargs"]).to(self.device)
        self.model.load_state_dict(ck["state_dict"]); self.model.eval()
        self.mean = np.asarray(ck["norm"]["mean"], np.float32)
        self.std = np.asarray(ck["norm"]["std"], np.float32)
        fs = cfg["fs"]
        self.sos = butter(cfg["filter_order"], [cfg["band"][0] / (fs / 2), cfg["band"][1] / (fs / 2)],
                          btype="band", output="sos")
        self.win = cfg["win"]
        self.reset()

    def reset(self):
        self.zi = None
        self.buf = np.zeros((self.cfg["model_kwargs"]["n_ch"], self.win), np.float32)  # == zero left-pad
        self.bad_hist = deque(maxlen=self.cfg["mic_hold"])
        self.prob_hist = deque(maxlen=max(1, self.cfg["smooth_k"]))
        self.last = (self.classes[0], np.eye(len(self.classes))[0])

    def update(self, p1, p2, p3, mic, run_model=True):
        x = np.array([p1, p2, p3], np.float64)
        if self.zi is None:
            self.zi = np.stack([sosfilt_zi(self.sos) * x[c] for c in range(3)])
        f = np.empty(3)
        for c in range(3):
            y, self.zi[c] = sosfilt(self.sos, x[c:c + 1], zi=self.zi[c])
            f[c] = y[0]
        bad = (not np.isfinite(mic)) or mic < self.cfg["mic_bad_low"] or mic > self.cfg["mic_bad_high"]
        self.bad_hist.append(bad)
        valid = 0.0 if any(self.bad_hist) else 1.0

        v = np.zeros(self.buf.shape[0], np.float32)
        v[:3] = (f - self.mean[:3]) / self.std[:3]
        v[3] = (mic - self.mean[3]) / self.std[3] if valid else 0.0
        v[4] = valid
        self.buf[:, :-1] = self.buf[:, 1:]; self.buf[:, -1] = v

        if run_model:
            with torch.no_grad():
                logits = self.model(torch.from_numpy(self.buf)[None].to(self.device))
                p = torch.softmax(logits, -1)[0].cpu().numpy()
            self.prob_hist.append(p)
            ps = np.mean(self.prob_hist, axis=0)
            self.last = (self.classes[int(ps.argmax())], ps)
        return self.last

