def bandpass_filter(data, lowcut=0.5, highcut=20.0, fs=50, order=2):
    nyquist = 0.5 * fs
    b, a = butter(order, [lowcut / nyquist, highcut / nyquist], btype='band')
    return filtfilt(b, a, data)

def preprocess_block(df):
    df = df.copy()
    df['Time_sec'] = (df['Time_ms'] - df['Time_ms'].iloc[0]) / 1000.0

    # Piezos: demean -> bandpass -> normalize per block
    for col in PIEZO_COLS:
        if col in df.columns:
            sig = bandpass_filter(df[col] - df[col].mean(), fs=SAMPLING_RATE_HZ)
            df[f'{col}_clean'] = sig / (np.std(sig) + 1e-9)

    # Mic: demean -> normalize per block (no bandpass; it's already a level/envelope)
    if 'Mic_Level' in df.columns:
        mic = df['Mic_Level'] - df['Mic_Level'].mean()
        df['Mic_Level_clean'] = mic / (np.std(mic) + 1e-9)

    return df

