def extract_features(window_df):
    features = {}
    for col in CLEAN_COLS:
        if col not in window_df.columns:
            continue
        sig = window_df[col].values

        # Whole-window features
        rms = np.sqrt(np.mean(sig**2))
        features[f'{col}_mean'] = np.mean(sig)
        features[f'{col}_std'] = np.std(sig)
        features[f'{col}_max'] = np.max(sig)
        features[f'{col}_min'] = np.min(sig)
        features[f'{col}_rms'] = rms
        features[f'{col}_p2p'] = np.ptp(sig)
        fft_vals = np.abs(np.fft.rfft(sig))
        features[f'{col}_energy'] = np.sum(fft_vals**2) / len(fft_vals)

        # Dominant frequency (talking vs. swallowing vs. cough differ in rhythm)
        freqs = np.fft.rfftfreq(len(sig), d=1 / SAMPLING_RATE_HZ)
        features[f'{col}_dom_freq'] = freqs[np.argmax(fft_vals[1:]) + 1]

        # Burst features: catch short events (coughs, swallows) hidden in 5 s
        n_sub = len(sig) // SUBWINDOW_SAMPLES
        sub_rms = [np.sqrt(np.mean(sig[j*SUBWINDOW_SAMPLES:(j+1)*SUBWINDOW_SAMPLES]**2))
                   for j in range(n_sub)]
        features[f'{col}_burst_max'] = np.max(sub_rms)
        features[f'{col}_burst_ratio'] = np.max(sub_rms) / (rms + 1e-9)
        features[f'{col}_burst_std'] = np.std(sub_rms)
    return features

