"""### Event-level results
For real-time use, what matters is whether each event gets caught, how quickly, and how many false alarms there are. A true event is **detected** if at least `EVENT_OVERLAP` of its samples are predicted as its class. **Latency** is the time from the true start to the first correct prediction inside the event. A **false alarm** is a predicted run of a non-Break class, at least `MIN_EVENT_S` long, that doesn't overlap any true event of that class.
"""

def segments(lbl):
    """[(cls, start, end_exclusive), ...] runs of equal labels."""
    if len(lbl) == 0:
        return []
    cut = np.flatnonzero(np.diff(lbl)) + 1
    starts = np.r_[0, cut]; ends = np.r_[cut, len(lbl)]
    return [(int(lbl[s]), int(s), int(e)) for s, e in zip(starts, ends)]

def event_metrics(y_true, y_pred, min_len=int(MIN_EVENT_S * FS), overlap=EVENT_OVERLAP):
    rows = {c: {"events": 0, "detected": 0, "latencies": [], "false_alarms": 0} for c in range(1, N_CLASSES)}
    true_segs = [s for s in segments(y_true) if s[0] >= 1]
    for c, s, e in true_segs:
        r = rows[c]; r["events"] += 1
        hit = (y_pred[s:e] == c)
        if hit.mean() >= overlap:
            r["detected"] += 1
            r["latencies"].append(np.argmax(hit) / FS)
    for c, s, e in segments(y_pred):
        if c >= 1 and e - s >= min_len:
            if not np.any(y_true[s:e] == c):
                rows[c]["false_alarms"] += 1
    return rows

agg = {c: {"events": 0, "detected": 0, "latencies": [], "false_alarms": 0} for c in range(1, N_CLASSES)}
total_min = 0.0
for b, p in oof_probs.items():
    y = blocks[b]["y"].copy()
    y[y < 0] = 0
    r = event_metrics(y, causal_smooth(p).argmax(1))
    total_min += len(y) / FS / 60
    for c in agg:
        for key in ("events", "detected", "false_alarms"):
            agg[c][key] += r[c][key]
        agg[c]["latencies"] += r[c]["latencies"]

