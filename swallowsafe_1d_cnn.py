"""## 6. Training and inference helpers"""

@torch.no_grad()
def predict_block_probs(model, feat_norm, batch=4096):
    """Per-sample class probabilities for a whole normalized block (T,C) -> (T,K). Same as streaming."""
    model.eval()
    pad = np.zeros((WIN - 1, N_CH), np.float32)
    X = torch.from_numpy(np.concatenate([pad, feat_norm]).T.copy())        # (C, T+WIN-1)
    W = X.unfold(1, WIN, 1).permute(1, 0, 2)                                # (T, C, WIN)
    out = []
    for i in range(0, len(W), batch):
        out.append(torch.softmax(model(W[i:i + batch].contiguous().to(DEVICE)), -1).cpu())
    return torch.cat(out).numpy()

def causal_smooth(p, k=SMOOTH_K):
    """Mean of the last k probability vectors (fewer at the start), identical to the streaming deque."""
    if k <= 1:
        return p
    c = np.cumsum(np.vstack([np.zeros((1, p.shape[1])), p]), 0)
    n = np.arange(1, len(p) + 1)
    lo = np.maximum(0, n - k)
    return (c[n] - c[lo]) / (n - lo)[:, None]

def class_weights(labels):
    counts = np.bincount(labels, minlength=N_CLASSES).astype(float)
    w = (counts.sum() / np.maximum(counts, 1)) ** CLASS_WEIGHT_POWER
    return torch.tensor(w / w.mean(), dtype=torch.float32)

def eval_blocks(model, ids, norm, smooth_k=SMOOTH_K):
    ys, ps = [], []
    for b in ids:
        p = causal_smooth(predict_block_probs(model, normalize(blocks[b]["feat"], norm)), smooth_k)
        ok = blocks[b]["target_ok"]
        ys.append(blocks[b]["y"][ok]); ps.append(p[ok].argmax(1))
    y, p = np.concatenate(ys), np.concatenate(ps)
    return f1_score(y, p, average="macro", labels=list(range(N_CLASSES)), zero_division=0)

def train_model(train_ids, val_ids=None, epochs=EPOCHS, seed=SEED, verbose=True):
    """Trains on train_ids. If val_ids is given, keeps the epoch with best smoothed macro-F1 on them."""
    set_seed(seed)
    norm = fit_norm([blocks[b]["feat"] for b in train_ids])
    ds = WindowDataset([normalize(blocks[b]["feat"], norm) for b in train_ids],
                       [blocks[b]["y"] for b in train_ids],
                       [blocks[b]["target_ok"] for b in train_ids],
                       stride=TRAIN_STRIDE, augment=True)
    loader = DataLoader(ds, batch_size=BATCH, shuffle=True, drop_last=True, num_workers=0)
    model = SwallowCNN(**MODEL_KWARGS).to(DEVICE)
    opt = torch.optim.AdamW(model.parameters(), lr=LR, weight_decay=WEIGHT_DECAY)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=LR, epochs=epochs, steps_per_epoch=len(loader))
    crit = nn.CrossEntropyLoss(weight=class_weights(ds.labels()).to(DEVICE), label_smoothing=LABEL_SMOOTHING)

    best_f1, best_state, best_ep, history = -1.0, None, epochs, []
    for ep in range(1, epochs + 1):
        model.train(); t0 = time.time(); tot = 0.0
        for xb, yb in loader:
            xb, yb = xb.to(DEVICE), yb.to(DEVICE)
            opt.zero_grad(set_to_none=True)
            loss = crit(model(xb), yb)
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), 5.0)
            opt.step(); sched.step()
            tot += loss.item() * len(yb)
        rec = {"epoch": ep, "loss": tot / (len(loader) * BATCH)}
        if val_ids:
            rec["val_macro_f1"] = eval_blocks(model, val_ids, norm)
            if rec["val_macro_f1"] > best_f1:
                best_f1, best_ep = rec["val_macro_f1"], ep
                best_state = copy.deepcopy(model.state_dict())
        history.append(rec)
        if verbose and (ep == 1 or ep % 5 == 0 or ep == epochs):
            print(f"  ep {ep:3d}  loss {rec['loss']:.4f}" +
                  (f"  val macro-F1 {rec['val_macro_f1']:.3f}" if val_ids else "") +
                  f"  ({time.time() - t0:.1f}s)")
    if best_state is not None:
        model.load_state_dict(best_state)
    return model, norm, best_ep, history

"""## 7. Blocked cross-validation
The folds are stratified so each one holds out some cough-session and some laugh-session blocks. Inside each training fold, a few blocks are held back as an inner validation set to pick the best epoch. The test blocks are never seen during training or epoch selection.
"""

def stratified_block_split(ids, n_groups, seed=SEED):
    """Deal blocks round-robin into n_groups, separately for each 'which classes does this block contain' type."""
    rng = np.random.RandomState(seed)
    kinds = {}
    for b in ids:
        key = tuple(sorted(set(blocks[b]["y"][blocks[b]["y"] >= 0].tolist())))
        kinds.setdefault(key, []).append(b)
    groups, k = [[] for _ in range(n_groups)], 0
    for key in sorted(kinds):
        for b in rng.permutation(kinds[key]):
            groups[k % n_groups].append(int(b)); k += 1
    return [sorted(g) for g in groups]

