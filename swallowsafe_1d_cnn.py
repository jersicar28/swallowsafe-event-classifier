"""## 4. Windowed dataset
Each block is left-padded with `WIN-1` zeros so every sample, including the first 2 s, gets a window ending exactly at that sample. The streaming classifier starts with the same zero buffer.
"""

def augment_window(x):
    """x: (C, WIN) tensor, normalized."""
    x[:3] *= torch.empty(3, 1).uniform_(*AUG_SCALE)
    x[3] *= float(torch.empty(1).uniform_(*AUG_SCALE))
    x[:4] += AUG_NOISE * torch.randn(4, x.shape[1])
    if torch.rand(1).item() < MIC_DROPOUT_P:
        x[4] = 0.0
    x[3] *= x[4]                                       # keep mic==0 wherever invalid
    return x

class WindowDataset(Dataset):
    def __init__(self, feats, ys, oks, stride=1, augment=False):
        pad = np.zeros((WIN - 1, N_CH), np.float32)
        self.X = [torch.from_numpy(np.concatenate([pad, f]).T.copy()) for f in feats]   # (C, T+WIN-1)
        self.Y = [torch.from_numpy(y.astype(np.int64)) for y in ys]
        idx = []
        for b, (y, ok) in enumerate(zip(ys, oks)):
            ends = np.arange(0, len(y), stride)
            ends = ends[ok[ends]]
            idx.append(np.stack([np.full(len(ends), b), ends], 1))
        self.index = np.concatenate(idx)
        self.augment = augment

    def __len__(self):
        return len(self.index)

    def __getitem__(self, i):
        b, e = self.index[i]
        x = self.X[b][:, e:e + WIN].clone()            # window's last column == original sample e
        if self.augment:
            x = augment_window(x)
        return x, self.Y[b][e]

    def labels(self):
        return np.array([int(self.Y[b][e]) for b, e in self.index])

"""## 5. Model
A small dilated residual 1D CNN with a receptive field of about 1 s. Its pooled features are the window mean, the window max and the mean of the newest 0.5 s, which emphasizes what is happening *now*.
"""

class ConvBlock(nn.Module):
    def __init__(self, cin, cout, k, dilation, p_drop):
        super().__init__()
        pad = (k - 1) * dilation // 2
        self.conv = nn.Conv1d(cin, cout, k, padding=pad, dilation=dilation)
        self.bn = nn.BatchNorm1d(cout)
        self.drop = nn.Dropout(p_drop)
        self.skip = nn.Conv1d(cin, cout, 1) if cin != cout else nn.Identity()

    def forward(self, x):
        return self.drop(F.relu(self.bn(self.conv(x)))) + self.skip(x)

class SwallowCNN(nn.Module):
    def __init__(self, n_ch=N_CH, n_classes=N_CLASSES, width=WIDTH, dropout=DROPOUT, recent=FS // 2):
        super().__init__()
        w2 = width // 2
        self.recent = recent
        self.body = nn.Sequential(
            ConvBlock(n_ch, w2, 7, 1, dropout),
            ConvBlock(w2, width, 5, 2, dropout),
            ConvBlock(width, width, 5, 4, dropout),
            ConvBlock(width, width, 3, 8, dropout),
        )
        self.head = nn.Sequential(
            nn.Linear(3 * width, 64), nn.ReLU(), nn.Dropout(dropout), nn.Linear(64, n_classes))

    def forward(self, x):                       # x: (B, C, WIN)
        h = self.body(x)
        feats = torch.cat([h.mean(-1), h.amax(-1), h[..., -self.recent:].mean(-1)], dim=1)
        return self.head(feats)

MODEL_KWARGS = dict(n_ch=N_CH, n_classes=N_CLASSES, width=WIDTH, dropout=DROPOUT, recent=FS // 2)
